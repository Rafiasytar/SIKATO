  tempat_tinggal_yang_ditempati VARCHAR(500),
  status_tanah_bangunan_tempat_tinggal_yang_ditempati VARCHAR(500),
  apakah_kepemilikan_lahan_tempat_tinggal_memiliki_dokumen_yang_resmi TEXT,
  luas_rumah VARCHAR(500),
  jenis_lantai_tempat_tinggal_terluas VARCHAR(500),
  jenis_dinding_sebagian_besar_rumah VARCHAR(500),
  jenis_atap VARCHAR(500),
  penerangan_rumah VARCHAR(500),
  besar_daya_listrik_pln VARCHAR(500),
  energi_untuk_memasak VARCHAR(500),
  tempat_pembuangan_sampah VARCHAR(500),
  fasilitas_mck VARCHAR(500),
  sumber_air_mandi_terbanyak_dari VARCHAR(500),
  fasilitas_jamban VARCHAR(500),
  jenis_kloset VARCHAR(500),
  sumber_air_minum_terbanyak_dari VARCHAR(500),
  tempat_pembuangan_air_limbah_septic_tank VARCHAR(500),
  rumah_berada_di_bawah_sutet_sutt_suttas VARCHAR(500),
  rumah_di_lereng_bukit_gunung VARCHAR(500),
  secara_keseluruhan_kondisi_rumah VARCHAR(500),
  blt_dana_desa VARCHAR(500),
  program_keluarga_harapan_pkh VARCHAR(500),
  bantuan_sosial_tunai VARCHAR(500),
  bantuan_umkm VARCHAR(500),
  bantuan_pendidikan_anak VARCHAR(500),
  bantuan_lainnya VARCHAR(500),
  berapa_rata_rata_pegeluaran_keluarga_dalam_sebulan_rupiah VARCHAR(500),
  kepemilikin_aset VARCHAR(500),
  apakah_memelihara_ternak TEXT,
  jumlah_kepemilikan_bidang_tanah VARCHAR(500),
  jumlah_lembar_pbb VARCHAR(500),
  nomor_nop_pbb VARCHAR(500),
  apakah_mempunyai_umkm TEXT,
  jika_punya_apa_nama_usahanya_dan_dibidang_apa VARCHAR(500),
  lokasi_usaha VARCHAR(500),
  apakah_lokasi_usahanya_sudah_ada_di_google_maps TEXT,
