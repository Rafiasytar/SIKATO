  rumah_tampak_depan TEXT,
  dalam_rumah_ruang_tamu TEXT,
  bantuan_rehap_rumah_tidak_layak_huni VARCHAR(500),
  alamat_lengkap VARCHAR(500),
  apakah_ada_anak_yang_putus_sekolah_kalau_ada_berapa_dan_sebutkan_nama_nama_dan_kapan_berhenti_sekolah_nya_sd_smp_sma TEXT,
  foto_buku_nikah TEXT,
  nama_enumerator_mahasiswa VARCHAR(500),
  periode_pendataan VARCHAR(500),
  nama_responden VARCHAR(500),
  jumlah_anggota_dalam_keluarga VARCHAR(500),
