  luas_sawah VARCHAR(500),
  luas_kebun_tanaman_muda VARCHAR(500),
  luas_kebun_tanaman_tua VARCHAR(500),
  luas_lahan_kosong VARCHAR(500),
  luas_kolam_ikan VARCHAR(500),
