-- Indexing untuk Kecepatan Query & Filter
CREATE INDEX IF NOT EXISTS idx_sensus_nomor_kk ON sensus_keluarga(nomor_kk);
CREATE INDEX IF NOT EXISTS idx_sensus_nama_kk ON sensus_keluarga(nama_kepala_keluarga);
CREATE INDEX IF NOT EXISTS idx_sensus_periode ON sensus_keluarga(periode_pendataan);
