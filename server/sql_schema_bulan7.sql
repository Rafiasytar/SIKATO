  rata_rata_produksi_panen_padi_pangan_lainnya_per_musim_panen VARCHAR(500),
  permasalahan_nomor_induk_berusaha_nib_dan_sertifikat_halal_pada_umkm TEXT,
  perkiraan_pendapatan_bulanan_pelaku_umkm_per_bulan VARCHAR(500),
